export const SYSTEM_LANGUAGES = ["en", "zh-Hans", "zh-Hant", "ja", "ko"] as const;
export type SystemLanguage = (typeof SYSTEM_LANGUAGES)[number];

export const SUMMARY_LANGUAGES = ["article", ...SYSTEM_LANGUAGES] as const;
export type SummaryLanguage = (typeof SUMMARY_LANGUAGES)[number];

export const SYSTEM_LANGUAGE_LABELS: Record<SystemLanguage, string> = {
  en: "English",
  "zh-Hans": "简体中文",
  "zh-Hant": "繁體中文",
  ja: "日本語",
  ko: "한국어"
};

export function isSystemLanguage(value: string | null | undefined): value is SystemLanguage {
  return (SYSTEM_LANGUAGES as readonly string[]).includes(value ?? "");
}

export function normalizeSystemLanguage(value: string | null | undefined): SystemLanguage {
  return isSystemLanguage(value) ? value : "en";
}

export function normalizeSummaryLanguage(value: string | null | undefined): SummaryLanguage {
  if (value === "article") return "article";
  return isSystemLanguage(value) ? value : "en";
}

export function pickLocale<T>(locale: SystemLanguage, table: Record<SystemLanguage, T>): T {
  return table[locale];
}

